import { env, createExecutionContext, waitOnExecutionContext } from 'cloudflare:test';
import { beforeEach, expect, it } from 'vitest';
import { createApp } from '../src/index.js';
import { hostedFetch } from '../src/hosted/oauth.js';
import { connectPlugin, pairCode } from '../src/hosted/relay.js';
import type { Env } from '../src/env.js';
const bindings:Env={...env,HOSTED_MCP_ENABLED:'true',CONSOLE_ORIGIN:'https://console.test',DEV_ONLY_FAKE_USER:''};
const app=createApp(),fileKey='eu8zGUOsrdyXXQqvJeyl1E';
async function run(path:string,init?:RequestInit){
 const ctx=createExecutionContext();
 const response=await hostedFetch(new Request('https://console.test'+path,init),bindings,ctx,app);
 await waitOnExecutionContext(ctx);return response;
}
const json=(body:unknown,cookie?:string,origin='https://console.test'):RequestInit=>({method:'POST',headers:{'Content-Type':'application/json',Origin:origin,...(cookie?{Cookie:cookie}:{})},body:JSON.stringify(body)});
beforeEach(async()=>{
 for(const table of ['hosted_operations','hosted_plans','hosted_connections','hosted_sources','hosted_consents','hosted_assistant_activity','hosted_browser_sessions','hosted_plugin_consents'])await env.DB.prepare(`DELETE FROM ${table}`).run();
 await env.DB.prepare("DELETE FROM rate_limits WHERE scope LIKE 'hosted:%'").run();
});
it('requires plugin approval without an account and separates file, browser and assistant authority',async()=>{
 const registration=await run('/oauth/register',json({client_name:'Accountless test',redirect_uris:['https://client.test/callback'],grant_types:['authorization_code','refresh_token'],response_types:['code'],token_endpoint_auth_method:'none'}));
 expect(registration.status).toBe(201);
 const client=await registration.json() as {client_id:string};
 const verifier='p'.repeat(64),digest=new Uint8Array(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(verifier)));
 const challenge=btoa(String.fromCharCode(...digest)).replace(/\+/g,'-').replace(/\//g,'_').replace(/=+$/,'');
 const query=new URLSearchParams({client_id:client.client_id,redirect_uri:'https://client.test/callback',response_type:'code',scope:'elf:read elf:write',resource:'https://console.test/mcp',state:'plugin-test',code_challenge:challenge,code_challenge_method:'S256'}).toString();
 const input={query,url:`https://www.figma.com/design/${fileKey}/Untitled`};
 expect((await run('/api/hosted-auth/start',json(input,undefined,'https://attacker.test'))).status).toBe(403);
 expect((await run('/api/hosted-auth/start',json({...input,query:query.replace('S256','plain')}))).status).toBe(400);
 const start=await run('/api/hosted-auth/start',json(input));expect(start.status).toBe(200);
 const pair=await start.json() as {handle:string;code:string;connectionId:string};
 const cookies=start.headers.getSetCookie();
 expect(cookies.some(c=>c.startsWith('__Host-elf-settings=')&&c.includes('HttpOnly')&&c.includes('Secure')&&c.includes('SameSite=Strict'))).toBe(true);
 const cookie=cookies.map(c=>c.split(';')[0]).join('; ');
 const finish=()=>run('/api/hosted/consent/finish',json({handle:pair.handle,approve:true},cookie));
 expect((await finish()).status).toBe(400);
 expect((await run(`/api/hosted/connections/${pair.connectionId}`)).status).toBe(401);
 await expect(connectPlugin(bindings,{code:pair.code,fileKey:'otherFile012345',fileName:'Other'},null)).rejects.toThrow();
 const connected=await connectPlugin(bindings,{code:pair.code,fileKey,fileName:'Untitled'},null);
 expect(connected.assistant).toMatchObject({clientName:'Accountless test',redirectHost:'client.test'});
 const approve={generation:connected.generation};
 expect((await run('/api/hosted-bridge/approve',json(approve,cookie))).status).toBe(400);
 expect((await run(`/api/hosted/connections/${pair.connectionId}/approve`,json({generation:connected.generation,fileKey,trust:'plugin'},cookie))).status).toBe(400);
 expect((await finish()).status).toBe(400);
 const pluginApproval=await run('/api/hosted-bridge/approve',{...json(approve),headers:{'Content-Type':'application/json',Authorization:`Bearer ${connected.session}`}});
 expect(pluginApproval.status).toBe(200);
 expect((await run('/api/hosted/consent/finish',json({handle:pair.handle,approve:true}))).status).toBe(401);
 const finished=await finish();expect(finished.status).toBe(200);
 const redirect=new URL((await finished.json() as {redirectTo:string}).redirectTo);
 expect(redirect.searchParams.get('state')).toBe('plugin-test');
 const tokenBody=new URLSearchParams({grant_type:'authorization_code',client_id:client.client_id,redirect_uri:'https://client.test/callback',code:redirect.searchParams.get('code')!,code_verifier:verifier,resource:'https://console.test/mcp'});
 const tokenResponse=await run('/oauth/token',{method:'POST',body:tokenBody});expect(tokenResponse.status).toBe(200);
 const token=await tokenResponse.json() as {access_token:string};
 expect((await finish()).status).toBe(400);
 expect((await run('/api/me',{headers:{Cookie:cookie}})).status).toBe(401);
 expect((await run('/api/hosted/assistants',{headers:{Authorization:`Bearer ${token.access_token}`}})).status).toBe(401);
 const call=async(name:string,args:unknown)=>{
  const response=await run('/mcp',{method:'POST',headers:{'Content-Type':'application/json',Accept:'application/json, text/event-stream',Authorization:`Bearer ${token.access_token}`},body:JSON.stringify({jsonrpc:'2.0',id:1,method:'tools/call',params:{name,arguments:args}})});
  return await response.json() as {result:{isError?:boolean;content:{text:string}[]}};
 };
 expect((await call('get_figma_pairing_code',{url:'https://www.figma.com/design/otherFile012345/Other'})).result.isError).toBe(true);
 const own=await call('figma_onboarding_status',{});
 expect(JSON.parse(own.result.content[0].text).connections).toHaveLength(1);
 const other=await pairCode(bindings,'other-owner','otherFile012345');
 expect((await call('list_collections',{connectionId:other.connectionId})).result.isError).toBe(true);
 const list=await run('/api/hosted/assistants',{headers:{Cookie:cookie}});
 const assistants=await list.json() as {assistants:{id:string}[]};expect(assistants.assistants).toHaveLength(1);
 expect((await run(`/api/hosted/assistants/${assistants.assistants[0].id}/disconnect`,json({},cookie,'https://attacker.test'))).status).toBe(403);
 expect((await run(`/api/hosted/assistants/${assistants.assistants[0].id}/disconnect`,json({},cookie))).status).toBe(200);
 const revoked=await run('/mcp',{method:'POST',headers:{'Content-Type':'application/json',Accept:'application/json, text/event-stream',Authorization:`Bearer ${token.access_token}`},body:JSON.stringify({jsonrpc:'2.0',id:2,method:'tools/list'})});
 expect(revoked.status).toBe(401);
});
